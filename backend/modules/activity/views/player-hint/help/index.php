Manage the hints that have been given to your platform players.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Hint ID`: The id of the hint
* `Hint`: The id and title of the hint
* `Status`: Whether the hint has been seen by the player
  * `1`: Pending, the player has not seen the hint yet
  * `0`: The hint has been shown to the player
* `Ts`: When the hint was given

The page provides the following actions:
* `Create Player Hint`: Give a hint to a player
