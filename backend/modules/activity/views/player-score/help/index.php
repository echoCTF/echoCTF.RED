Manage the total scores of your platform players.

These records are maintained by the system as score events are processed.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Points`: The total points of the player
* `Academic`: The academic group of the player
* `Ts`: When the score was last updated

The page provides the following actions:
* `Create Player Score`: Create a score entry for a player
* `Export Top15 CSV`: Export the top 15 players to a CSV file
* `Export CSV`: Export all the scores to a CSV file
