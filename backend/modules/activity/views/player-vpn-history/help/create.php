Create a new VPN history record for a player.

These records are normally created by the system as players connect to the VPN.

The form fields include:
* `Player ID`: The id of the player the record belongs to
* `Vpn Remote Address`: The remote IP address of the player connection
* `Vpn Local Address`: The local IP address assigned to the player on the VPN
* `Ts`: When the connection was recorded
