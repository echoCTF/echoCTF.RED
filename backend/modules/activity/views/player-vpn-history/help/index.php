Manage the VPN connection history of your platform players.

These records are created by the system as players connect to the VPN.

The displayed fields include:
* `ID`: The record id
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Vpn Remote Address`: The remote IP address of the player connection
* `Vpn Local Address`: The local IP address assigned to the player on the VPN
* `Ts`: When the connection was recorded

The page provides the following actions:
* `Truncate VPN History`: Delete all the recorded VPN history
