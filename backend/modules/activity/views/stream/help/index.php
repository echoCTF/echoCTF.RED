Manage the activity stream entries of your platform players.

These records are created by the system as players perform actions on the platform, such as capturing flags or solving challenges.

The displayed fields include:
* `ID`: The record id
* `Formatted`: The stream entry as it is shown to players
* `Academic`: The academic group of the player
* `Player ID`: The id of the player
* `Model`: The type of the event (e.g. treasure, finding, headshot)
* `Model ID`: The id of the record the event refers to
* `Points`: The points the player got from the event

The page provides the following actions:
* `Create Stream`: Create a new stream entry manually
