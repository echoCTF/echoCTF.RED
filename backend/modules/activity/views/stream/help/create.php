Create a new stream entry for a player.

These records are normally created by the system as players perform actions on the platform.

The form fields include:
* `Player ID`: The player that the stream entry will belong to
* `Model`: The type of the event the entry refers to
* `Model ID`: The id of the record the event refers to
* `Points`: The points awarded to the player
* `Title`: The title shown to the owner and moderators
* `Message`: The message shown to the owner and moderators
* `Pubtitle`: The title shown to everyone on the public stream
* `Pubmessage`: The message shown to everyone on the public stream
