Manage the treasures that have been given to your platform players.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Target ID`: The id of the target the treasure belongs to
* `Treasure ID`: The id of the treasure
* `Treasure`: The name of the treasure
* `Points`: The points awarded for the treasure
* `Ts`: When the treasure was recorded

The page provides the following actions:
* `Create Player Treasure`: Give a treasure to a player
