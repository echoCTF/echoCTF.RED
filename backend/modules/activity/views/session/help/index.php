Manage the active sessions of your platform players.

These records are created by the system as players log in to the frontend.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `IP`: The IP address the player logged in from
* `sessionID`: The session identifier
* `Expire`: When the session expires
* `TS`: When the session was created

The page provides the following actions:
* `Delete expired`: Delete all expired sessions
* `Mass Delete`: Delete all sessions matching the currently applied filters
