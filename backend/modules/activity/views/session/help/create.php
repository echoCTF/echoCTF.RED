Create a new session record for a player.

These records are normally created by the system when players log in to the frontend.

The form fields include:
* `sessionID`: The session identifier
* `Expire`: When the session expires
* `Data`: The session data
* `Player ID`: The id of the player the session belongs to
* `IP`: The IP address the player logged in from
* `TS`: When the session was created
