Manage the answers players have given to challenge questions.

The displayed fields include:
* `ID`: The record id
* `Question ID`: The id of the question
* `Challenge ID`: The id of the challenge the question belongs to
* `Question`: The name of the question
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Points`: The points awarded for the question
* `Ts`: When the answer was recorded

The page provides the following actions:
* `Create Player Question`: Assign a question answer to a player
