Manage the findings that have been given to your platform players.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Target ID`: The id of the target the finding belongs to
* `Finding ID`: The id of the finding
* `Finding`: The name of the finding
* `Points`: The points awarded for the finding
* `Ts`: When the finding was recorded

The page provides the following actions:
* `Create Player Finding`: Give a finding to a player
