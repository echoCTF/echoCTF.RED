Manage the writeup activations players have made on your targets.

These records are created when players activate writeups for a target, which may cost them some points.

The displayed fields include:
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Target ID`: The id of the target
* `Target`: The name and IP of the target
* `Cost`: The points the player paid for the activation
* `Created At`: When the activation happened

The page provides the following actions:
* `Create Player Target Help`: Create an activation record manually
