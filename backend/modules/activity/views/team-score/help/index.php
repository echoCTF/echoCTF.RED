Manage the total scores of your platform teams.

These records are maintained by the system as team score events are processed.

The displayed fields include:
* `Team ID`: The id of the team
* `Team`: The name of the team
* `Academic`: The academic group of the team
* `Points`: The total points of the team
* `Ts`: When the score was last updated

The page provides the following actions:
* `Create Team Score`: Create a score entry for a team
* `Export Top15 CSV`: Export the top 15 teams to a CSV file
* `Export Top15 w/ players CSV`: Export the top 15 teams along with their players to a CSV file
