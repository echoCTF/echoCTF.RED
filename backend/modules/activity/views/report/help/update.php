Update an existing report and moderate it.

The fields used are as following:
* `Title`: The title of the report
* `Player ID`: The player that the report belongs to
* `Body`: The body of the report, including full details
* `Status`: The moderation status of the report
  * `Pending`: The report is awaiting moderation
  * `Invalid`: The report is considered invalid
  * `Approved`: Approving it grants the player the points you fill in below
* `Points`: The points to be awarded to the player for this report
* `Modcomment`: A comment from the moderator about the report
* `Pubtitle`: A message shown on the public stream when the report is approved
* `Pubbody`: A detailed description of the report shown in public spots of the pUI
