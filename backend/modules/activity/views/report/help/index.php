Manage the reports submitted by your platform players.

Players submit reports and moderators review them, awarding points when approved.

The displayed fields include:
* `ID`: The record id
* `Title`: The title of the report
* `Player ID`: The id of the player
* `Player`: The username of the player
* `Body`: The body of the report
* `Status`: The moderation status of the report
  * `Pending`: The report is awaiting moderation
  * `Approved`: The report was approved by a moderator
  * `Invalid`: The report was marked invalid

The page provides the following actions:
* `Create Report`: Create a new report
