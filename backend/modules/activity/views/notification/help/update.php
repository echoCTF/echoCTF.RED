Update an existing notification for a player.

The fields used are as following:
* `Player ID`: The player that the notification is sent to
* `Category`: The notification type (`swal:` prefixed ones invoke a modal popup)
* `Archived`: Whether the notification is archived (default: no)
* `Online`: Limit the notification to online players only
* `On VPN`: Limit the notification to players on the VPN only
* `Title`: The notification title
* `Body`: The notification body
