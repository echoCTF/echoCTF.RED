Create a new notification for a player.

The form fields include:
* `Player ID`: The player that we will send the notification
* `Category`: The notification type (`swal:` prefixed ones invoke a modal popup)
* `Archived`: Should the notification be archived? (default: no)
* `Online`: Notify only online players
* `On VPN`: Notify only players on the VPN
* `Title`: The notification title
* `Body`: The notification body
