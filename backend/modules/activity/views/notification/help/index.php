Manage the notifications that are sent to your platform players.

The displayed fields include:
* `ID`: The record id
* `Player`: The player the notification was sent to
* `Category`: The type of the notification
* `Title`: The notification title
* `Archived`: Whether the notification is archived or still pending
* `Created At`: When the notification was created

The page provides the following actions:
* `Create`: Create a new notification
* `Rotate`: Clear old archived and pending notifications based on the default retention settings
* `Mass Delete`: Delete all notifications matching the currently applied filters
