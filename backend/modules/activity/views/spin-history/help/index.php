Manage the history of target spins.

These records are created by the system when entries from the spin queue are processed.

The displayed fields include:
* `ID`: The record id
* `Target ID`: The id of the target
* `Target`: The name of the target
* `Player ID`: The id of the player that requested the spin
* `Player`: The username of the player
* `Created At`: When the spin was requested
* `Updated At`: When the spin was processed

The page provides the following actions:
* `Create`: Create a new spin history record
* `Truncate`: Delete all the spin history records
