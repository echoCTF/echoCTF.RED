Create a new VPN certificate record for a player.

Form fields include:
* `Player ID`: The player that this SSL will belong to
* `Serial`: The serial number assigned to the certificate
* `Subject`: The certificate subject, stored serialized
* `Csr`: The certificate signing request
* `Crt`: The certificate
* `Privkey`: The private key
* `Ts`: Timestamp of the record, set to the current time on save
