Update an existing Crl entry holding the certificate material of a revoked player certificate.

Fields that can be updated:
* `Player ID`: The player that this entry will belong
* `Subject`: The subject of the revoked certificate
* `Csr`: The certificate signing request of the certificate
* `Crt`: The revoked certificate itself
* `Privkey`: The private key of the certificate
* `Ts`: Timestamp of the entry
