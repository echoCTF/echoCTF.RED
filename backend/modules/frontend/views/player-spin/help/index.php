Manage the target spin counters and limits for each player.

The displayed fields include:
* `Player ID`: The player this record belongs to
* `Username`: Link to the player's full profile
* `Counter`: Spins used for the current day
* `Perday`: Daily spin limit for the player
* `Max instances`: Concurrent private target instances this player can have
* `Total`: Total spins used by the player
* `Updated At` / `Ts`: When the counters were last updated and the record timestamp

The page provides the following actions:
* `Create Spin`: Add a new spin counter record
* `Reset all spins`: Zero the spin counter of every player
