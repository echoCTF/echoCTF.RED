Create a new spin counter record for a player.

Form fields include:
* `Player ID`: The player that this entry will belong to
* `Counter`: Spins used for the current day
* `Perday`: Daily spin limit for the player
* `Max instances`: Concurrent private target instances this player can have, subscriptions add and remove their own value on top of this
* `Total`: Total spins used by the player
* `Updated At`: When the counters were last updated
