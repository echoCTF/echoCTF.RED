Track when each player was last seen on the frontend UI, the VPN and which IPs they used.

The displayed fields include:
* `Player ID`: The player id this record belongs to
* `Username`: Link to the player's full profile
* `On Pui`: When the player was last active on the frontend UI
* `On Vpn`: When the player was last active on the VPN
* `Vpn Remote Address`: The remote IP of the player's VPN connection
* `Vpn Local Address`: The local IP assigned to the player's VPN session
* `Signup IP`: The IP the player signed up from
* `Signin IP`: The IP the player last signed in from
* `Ts`: Timestamp of the record
