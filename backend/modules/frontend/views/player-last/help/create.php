Create a new player last activity record.

Form fields include:
* `On Pui`: When the player was last active on the frontend UI
* `On Vpn`: When the player was last active on the VPN
* `Vpn Remote Address Octet`: The remote IP of the player's VPN connection
* `Vpn Local Address Octet`: The local IP assigned to the player's VPN session
* `Signin Ipoctet`: The IP the player last signed in from
* `Signup Ipoctet`: The IP the player signed up from
