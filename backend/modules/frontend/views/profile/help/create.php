Create a new player profile.

Form fields include:
* `ID`: The profile id used for the player url
* `Player ID`: The player that this profile will belong to
* `Country`: The country of the player
* `Visibility`: Player profile visibility
* `Bio`: The profile bio text
* `Pending Progress` / `Approved Avatar` / `Avatar`: Avatar related flags and filename
* `Discord` / `Twitter` / `Github` / `echoCTF.RED` / `Htb` / `Youtube` / `Twitch`: Social links of the player
* `Terms And Conditions` / `Mail Optin` / `Gdpr`: The legal consents of the player
