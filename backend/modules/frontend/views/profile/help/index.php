Manage the player profiles of your platform.

The displayed fields include:
* `ID`: The profile id, used in the player profile url
* `Player ID`: The player the profile belongs to
* `Username`: The username of the profile owner
* `Bio`: The profile bio text
* `Country`: The country of the player
* `Visibility`: Who can see the profile, private, public or ingame
* `Twitter` / `Github` / `Discord` / `echoCTF.RED`: The social handles of the player

The page provides the following actions:
* `Create Profile`: Add a new profile for a player
* `Fail Validate`: List the profiles that fail their validation rules
