Update the details of an existing player, including their account status and credentials.

The fields used are as following:
* `Username`: The username of the player
* `Fullname`: The fullname of the player
* `Academic`: Academic grouping number for the player (if any)
* `Email`: The email address of the player
* `Type`: Choose the type of the player, either offense or defense
* `New Password`: Choose a password for the player
* `Activkey`: The activation key, generated automatically by the application
* `Auth Key`: The authentication key used for cookie validation, generated automatically if empty
* `Active`: Whether the player is active or not
* `Status`: Account status
