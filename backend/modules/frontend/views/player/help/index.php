Manage the players registered on your platform.

The displayed fields include:
* `Username`: Link to the player's full profile
* `Email`: The email address of the player
* `VPN IP` / `Online`: The local IP of the player's VPN session and whether they are online right now
* `Academic`: The academic group of the player
* `Status`: Account status, rows that fail their validation rules show up in red
* `Approval`: The approval stage of the player, shown when approvals are required

The page provides the following actions:
* `Create Player`: Add a new player, a VPN certificate is generated for it
* `Import Players` / `Export Full Players`: Bulk import players from CSV or export all player details
* `Fail Validate` / `Reset All player data` / `Reset All player progress`: List players failing validation, wipe all player data or reset all player progress
