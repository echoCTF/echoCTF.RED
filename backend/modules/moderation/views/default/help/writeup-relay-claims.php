Lists the **individual treasure claims** behind writeup relays found by shared IP. The *fake* is a zero point player holding writeups for a target, the *beneficiary* shares an IP with the fake (signup, signin, or VPN against the fake's signin IP) and claimed a treasure on the same target after the activation, without activating the writeups.

### Columns
* **Points / base**: the points the claim gave next to the treasure base points. The beneficiary never activated the writeups, so their claims are not reduced. Full points on a target the fake holds writeups for is exactly what the relay gains.

### Notes
* Only treasures are listed here, findings are counted on the *Writeup Relays (IP)* page.
* IPs come from `player_last`, so they are the latest known values. Shared networks produce false positives.
