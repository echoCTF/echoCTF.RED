Lists the writeup hoarders, players with zero points that have activated writeups. Writeups are meant for players who solved the target, so scoreless accounts with a pile of activations are usually there for the writeups, not the game.

The displayed fields include:
* `ID`: The player id
* `Avatar`: The player avatar
* `Username`: The player username, links to the full profile
* `Affiliation`: The affiliation from the player metadata, links to the identification file when one exists, only shown when both player approval and identification are required
* `Email`: The player email
* `VPN IP`: The VPN address of the player's last session
* `Online`: Whether the player is currently online
* `Activated Writeups`: How many target writeups the player activated
* `Academic`: Whether the account is academic
* `Approval`: The approval state of the account, only shown when player approval is required
* `Type`: Offense or defense, only shown when a defense scenario is set
* `Created`: When the account was created

The page provides the following actions:
* Two icons on the header row that mass delete, or delete and ban, every player matching the current filters
* Per player, the usual moderation actions: full profile, clear or disconnect VPN, generate SSL, activate, mail activation, reset activkey, approve, reject, set deleted, delete, ban

Players drawn in red fail the player validation rules.
