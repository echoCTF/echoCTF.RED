Manage the findings players can discover on your targets, such as open ports and services.

The displayed fields include:
* `Name`: The name of the finding
* `Pubname`: The name shown in public places
* `Points`: Points awarded when the finding is discovered
* `Protocol`: The protocol of the finding (TCP, UDP or ICMP)
* `Target`: The id, name and IP of the target
* `Port`: The port of the service for the finding
* `Stock`: How many times the finding can be awarded
* `Discovered`: How many players have discovered the finding

The page provides the following actions:
* `Create Finding`: Add a new finding
