Update an existing finding, for example its points, port or stock.

Fields:
* `Name`: Internal name of the finding
* `Pubname`: Public name of the finding
* `Description`: Internal description
* `Pubdescription`: Public description
* `Points`: Points for discovering the finding
* `Stock`: Award limit of the finding (-1 for unlimited)
* `Protocol`: TCP, UDP or ICMP
* `Target`: Which target the finding is on
* `Port`: Service port of the finding
