Create a new finding for one of your targets.

Form fields include:
* `Name`: The name of the finding (not shown in public places)
* `Pubname`: The name shown in public places like streams
* `Description`: A short description not shown in public places
* `Pubdescription`: A short description shown in public places
* `Points`: Points awarded when a player discovers the finding
* `Stock`: How many times the finding can be awarded before it is depleted (-1 for unlimited)
* `Protocol`: The protocol of the finding
* `Target`: The target the finding belongs to
* `Port`: The port the service listens on (use 0 for icmp)
