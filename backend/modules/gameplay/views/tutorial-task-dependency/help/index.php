Manage the dependencies of your tutorial tasks. Each dependency ties a task to an item the player has to complete.

The displayed fields include:
* `ID`: The record id
* `Tutorial Task ID`: The tutorial task the dependency belongs to
* `Item ID`: The id of the item the task depends on
* `Item`: The item the dependency refers to

The page provides the following actions:
* `Create Tutorial Task Dependency`: Add a new dependency to a task
