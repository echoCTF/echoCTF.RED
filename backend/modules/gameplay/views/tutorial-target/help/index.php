Attach targets to a tutorial so players get a machine to work through its tasks.

The displayed fields include:
* `Tutorial ID`: The tutorial the target is assigned to
* `Title`: The title of the tutorial
* `Target ID`: The target assigned to the tutorial
* `Name`: The name of the target
* `Ipoctet`: The IP of the target
* `Weight`: An ordering weight

The page provides the following actions:
* `Create Tutorial Target`: Assign a target to a tutorial
