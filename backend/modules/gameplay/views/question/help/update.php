Update an existing question, its answer code, points or the challenge it belongs to.

Fields:
* `Challenge`: Challenge the question is attached to
* `Name`: Title of the question
* `Description`: The full detail of the question
* `Points`: Awarded points for the answer
* `Player Type`: Offense, defense or both
* `Code`: The answer code a player submits
* `Weight`: Ascending ordering weight for the question
