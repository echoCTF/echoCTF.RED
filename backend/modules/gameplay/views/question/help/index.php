Manage the questions that belong to your challenges. Players claim each question by providing its answer code.

The displayed fields include:
* `ID`: The record id
* `Challenge ID`: The challenge the question belongs to
* `Challenge Name`: The name of the challenge
* `Name`: The name/title of the question
* `Description`: The question in full detail
* `Points`: Points awarded for answering the question
* `Code`: The answer code players must provide
* `Answered`: How many players have answered the question

The page provides the following actions:
* `Create Question`: Add a new question
