Create a new question and attach it to one of your challenges.

Form fields include:
* `Challenge`: The challenge this question is part of
* `Name`: The name/title of the question
* `Description`: The actual question in full detail
* `Points`: Points awarded for answering the question
* `Player Type`: Choose the player type (offense, defense or both)
* `Code`: The answer to the question, in the form of a flag to be claimed
* `Weight`: Ordering weight of the question, ascending (defaults to 0)
