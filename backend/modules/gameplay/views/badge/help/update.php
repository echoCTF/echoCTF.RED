Update an existing badge or change which findings and treasures it requires.

Fields:
* `Name`: Badge name
* `Pubname`: Public facing name
* `Description`: Scenario of the badge
* `Pubdescription`: Public scenario text, keep it free of hostnames, IPs, services and ports
* `Points`: Awarded points for the badge
* `Select Findings`: Findings the player needs before the badge is awarded
* `Select Treasures`: Treasures the player needs before the badge is awarded
