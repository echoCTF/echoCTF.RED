Create a new badge. A badge is granted when a player has claimed the treasures and findings you tie to it.

Form fields include:
* `Name`: The name of the badge
* `Pubname`: The name shown on public locations (e.g. streams)
* `Description`: The scenario of the badge and what players have to do to get it
* `Pubdescription`: A public description that leaks no hostnames, IPs, services or ports
* `Points`: Points awarded when a player/team gets this badge
* `Select Findings`: The findings required for the badge
* `Select Treasures`: The treasures required for the badge
