Manage the badges awarded to players that collect a set of findings and treasures.

The displayed fields include:
* `ID`: The record id
* `Name`: The name of the badge
* `Pubname`: The name shown on public locations
* `Description`: The scenario of the badge and what players have to do
* `Pubdescription`: A public description without leaking target details
* `Points`: Points awarded when a player gets the badge

The page provides the following actions:
* `Create Badge`: Add a new badge
