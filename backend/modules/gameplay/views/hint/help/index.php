Manage the hints players receive as they progress through your event.

The displayed fields include:
* `Title`: Short hint title
* `Message`: The hint message details
* `Badge ID`: The badge a player needs before the hint is shown
* `Finding ID`: The finding a player needs before the hint is shown
* `Treasure ID`: The treasure a player needs before the hint is shown
* `Question ID`: The question a player needs to answer before the hint is shown
* `Player Type`: Whether the hint is for offense, defense or both
* `Active`: Whether the hint is active

The page provides the following actions:
* `Create Hint`: Add a new hint
