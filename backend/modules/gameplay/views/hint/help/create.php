Create a new hint for your players.

Form fields include:
* `Title`: Short hint title
* `Player Type`: Choose the player type the hint is for
* `Message`: The descriptive hint message details
* `Category`: Category of the hint
* `Badge`: Give this hint to users who have the given badge
* `Finding`: Give this hint to users who have the given finding
* `Treasure`: Give this hint to users who have the given treasure
* `Points User`: Give this hint to users who have reached the given points
* `Points Team`: Give this hint to teams who have reached the given points
* `Timeafter`: Give this hint after this many seconds to active users
* `Active`: Whether the hint is active
