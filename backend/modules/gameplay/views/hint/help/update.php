Update an existing hint or change the conditions under which it is given to players.

Fields:
* `Title`: The hint title
* `Player Type`: Offense, defense or both
* `Message`: The hint message body
* `Category`: The hint category
* `Badge`: Shown to players that have the selected badge
* `Finding`: Shown to players that have the selected finding
* `Treasure`: Shown to players that have the selected treasure
* `Points User`: Shown when a user reaches these many points
* `Points Team`: Shown when a team reaches these many points
* `Timeafter`: Shown this many seconds after the start of the event
* `Active`: Whether the hint is active or inactive
