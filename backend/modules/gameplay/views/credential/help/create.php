Create a new credential for a target.

Form fields include:
* `Target`: The target system the credential is for
* `Service`: The service this credential is used on
* `Title`: The title of the credential
* `Pubtitle`: The public title of the credential
* `Username`: The username part of the credential
* `Password`: The password part of the credential
* `Points`: The amount of points for this credential
* `Player Type`: Whether the credential is for offense, defense or both players
* `Stock`: How many of this credential are available
