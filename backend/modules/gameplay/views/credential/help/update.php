Update an existing credential record, for example its login pair, points or remaining stock.

Fields:
* `Target`: Target the credential is tied to
* `Service`: Service of the credential
* `Title`: Credential title
* `Pubtitle`: Public credential title
* `Username`: The login username
* `Password`: The login password
* `Points`: Points for the credential
* `Player Type`: Offense, defense or both
* `Stock`: Remaining stock of the credential
