Manage the challenges your players can solve by answering questions.

The displayed fields include:
* `Name`: The name of the challenge
* `Active`: Whether the challenge is active
* `Public`: Whether the challenge is public
* `Timer`: Whether solving the challenge is timed
* `Category`: The category the challenge belongs to
* `Difficulty`: The difficulty of the challenge
* `Description`: The full scenario of the challenge
* `Player Type`: Whether the challenge is for offense, defense or both players

The page provides the following actions:
* `Create Challenge`: Add a new challenge
