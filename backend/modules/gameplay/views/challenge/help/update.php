Update an existing challenge, its file and availability. Questions attached to the challenge are managed from the challenge questions pages.

The fields used are as following:
* `Name`: Challenge name
* `Active`: Is the challenge active
* `Public`: Is the challenge public
* `Timer`: Keep a timer for solving
* `Icon`: Challenge icon in raw html
* `Category`: Category of the challenge
* `Difficulty`: Easy, medium, hard or very hard
* `Description`: Full scenario of the challenge
* `Player Type`: Offense, defense or both
* `Filename`: The filename shown to participants for download
* `File`: The challenge file upload
