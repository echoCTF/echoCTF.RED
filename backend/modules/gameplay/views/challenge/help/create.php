Create a new challenge. Questions are added separately from the "Gameplay"->"Challenge Questions" area.

Form fields include:
* `Name`: The name of the challenge
* `Active`: Whether the challenge is active
* `Public`: Whether the challenge is public
* `Timer`: Whether to keep a timer for solving the challenge
* `Icon`: Challenge icon (raw html)
* `Category`: The category this challenge belongs to
* `Difficulty`: The difficulty of the challenge (easy, medium, hard or very hard)
* `Description`: The full description/scenario of the challenge, no questions here
* `Player Type`: Whether the challenge is available to offense or defense players/teams
* `Filename`: The name shown to the player for the download
* `File`: Upload the challenge file
