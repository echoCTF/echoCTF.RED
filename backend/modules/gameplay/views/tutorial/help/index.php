Manage the tutorials that walk players through tasks on your targets. Tasks and target associations are managed from their own pages.

The displayed fields include:
* `ID`: The record id
* `Title`: The title of the tutorial
* `Description`: The description of the tutorial
* `Created At`: When the tutorial was created
* `Updated At`: When the tutorial was last updated

The page provides the following actions:
* `Create Tutorial`: Add a new tutorial
