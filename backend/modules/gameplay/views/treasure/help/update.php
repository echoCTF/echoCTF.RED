Update an existing treasure. Adjust the flag, its points, descriptions and claim limits from here.

The fields used are as following:
* `Target`: Which target the treasure lives on
* `Name`: Treasure name
* `Pubname`: The name shown publicly
* `category`: Category of the flag
* `Description`: Internal description of the treasure
* `Pubdescription`: The description shown publicly
* `Points`: Awarded points for claiming the treasure
* `Player Type`: Offense, defense or both players can claim it
* `Csum`: Checksum for a file attached to the treasure
* `Appears`: Claim limit for the treasure (-1 for unlimited)
* `Effects`: When the claim counter is retracted (per player, per team or once total)
* `Code`: The flag itself
* `Flag location`: Where the flag is found
* `Suggestion`: How the player can get to the flag
* `Solution`: Steps needed to get the flag
* `Weight`: Ordering weight
