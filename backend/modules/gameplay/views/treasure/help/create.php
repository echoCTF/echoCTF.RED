Create a new treasure/flag for one of your targets.

Form fields include:
* `Target`: The target the treasure is hidden on
* `Name`: A name for the treasure
* `Pubname`: A public name for the treasure, shown on streams and other public places
* `category`: A category for this flag
* `Description`: A short description of the treasure
* `Pubdescription`: A short description of the treasure shown on public places
* `Points`: Points awarded to a player which claims this treasure
* `Player Type`: Whether the treasure is for offense, defense or both players
* `Csum`: Used when a file is attached to the treasure
* `Appears`: How many times the treasure may be claimed (-1 for unlimited)
* `Effects`: How the appearances are retracted (once per player, once per team or once total)
* `Code`: The actual treasure/flag
* `Flag location`: The location where the flag can be found
* `Suggestion`: A suggestion for the player on how to get the flag
* `Solution`: The steps required to get the flag, sort of like a write-up
* `Weight`: Ordering weight for the treasure
