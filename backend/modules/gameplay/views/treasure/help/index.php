Manage the flags (treasures) that are hidden on your targets.

The displayed fields include:
* `ID`: The record id
* `Target ID`: The target the treasure is hidden on
* `Target`: The name and IP of the target
* `Name`: The treasure name
* `Pubname`: A public name for the treasure
* `category`: Flag category (other, env, root, system, app)
* `Points`: Points awarded when a player claims the treasure
* `Player Type`: Whether the treasure is for offense, defense or both
* `Appears`: How many times the treasure may be claimed
* `Code`: The actual treasure flag
* `Discovered`: Number of players that have claimed the treasure
* `Weight`: An ordering weight

The page provides the following actions:
* `Create Treasure`: Add a new treasure
* `Validate Treasure`: Find the player a claimed code belongs to
