Update the details of an existing achievement, including its points, public description and claim code.

The fields used are as following:
* `Name`: Achievement name
* `Pubname`: Public facing name
* `Description`: Scenario of the achievement
* `Pubdescription`: Public scenario text without hostnames, IPs, services, ports etc
* `Points`: Awarded points for completing the achievement
* `Player Type`: Offense, defense or both
* `Appears`: How many times the achievement can be claimed
* `Effects`: If the achievement counts per user, per team or total
* `Code`: The code players provide to claim it
