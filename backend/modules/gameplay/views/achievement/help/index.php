Manage the achievements your players can claim by providing a code. Achievements are special awards outside the normal target and challenge flow.

The displayed fields include:
* `ID`: The record id
* `Name`: The name of the achievement
* `Pubname`: The name shown on public locations
* `Description`: The scenario of the achievement and what players have to do
* `Pubdescription`: A public description without leaking target details
* `Player Type`: Whether it is for offense, defense or both types of players

The page provides the following actions:
* `Create Achievement`: Add a new achievement
