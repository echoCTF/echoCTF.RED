Create a new achievement for your players to claim.

Form fields include:
* `Name`: The name of the achievement
* `Pubname`: The name shown on public locations (e.g. streams)
* `Description`: The scenario of the achievement and what players have to do
* `Pubdescription`: A public description that leaks no target details
* `Points`: Points awarded when a player/team completes this achievement
* `Player Type`: Whether it is for offense, defense or both players
* `Appears`: How many times the achievement can be claimed
* `Effects`: Whether this achievement is only for users, only for teams or both
* `Code`: The code/flag players must provide in order to claim this achievement
